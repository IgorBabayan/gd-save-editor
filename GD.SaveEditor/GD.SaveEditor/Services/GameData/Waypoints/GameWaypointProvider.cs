using System.IO;
using GD.SaveEditor.Services.GameData.Database;
using Microsoft.Data.Sqlite;

namespace GD.SaveEditor.Services.GameData.Waypoints;

/// <summary>The waypoints of the game (the <c>waypoints</c> table of <c>database.db</c>).</summary>
public interface IGameWaypointProvider
{
    /// <summary>Every known waypoint, by campaign and name; empty when the database has none (not generated yet).</summary>
    IReadOnlyList<GameWaypoint> GetWaypoints();

    /// <summary>Forgets the cached waypoints, e.g. after the database was migrated.</summary>
    void ClearCache();
}

public sealed class GameWaypointProvider(IGameTextProvider texts) : IGameWaypointProvider
{
    private readonly Lock _lock = new();
    private IReadOnlyList<GameWaypoint>? _cache;

    public IReadOnlyList<GameWaypoint> GetWaypoints()
    {
        lock (_lock)
            return _cache ??= Read();
    }

    public void ClearCache()
    {
        lock (_lock)
            _cache = null;
    }

    private IReadOnlyList<GameWaypoint> Read()
    {
        if (!File.Exists(GameDataPaths.DatabaseFile))
            return [];

        var rows = new List<(string Uid, string Record, string? NameTag, int Campaign, int Order)>();
        try
        {
            using var connection = new SqliteConnection(new SqliteConnectionStringBuilder
            {
                DataSource = GameDataPaths.DatabaseFile,
                Mode = SqliteOpenMode.ReadOnly
            }.ToString());
            connection.Open();

            using var command = connection.CreateCommand();
            command.CommandText = "SELECT uid, record, name_tag, campaign, ordinal FROM waypoints;";
            using var reader = command.ExecuteReader();
            while (reader.Read())
            {
                rows.Add((reader.GetString(0), reader.GetString(1), reader.IsDBNull(2) ? null : reader.GetString(2),
                    reader.GetInt32(3), reader.GetInt32(4)));
            }
        }
        catch (SqliteException)
        {
            // No waypoints table yet (database generated by an older version) or a damaged database.
            return [];
        }

        return rows
            .Where(r => Enum.IsDefined((GameWaypointCampaign)r.Campaign))
            .Select(r => new GameWaypoint(r.Uid, r.Record, DisplayName(r.NameTag, r.Record), (GameWaypointCampaign)r.Campaign, r.Order))
            .OrderBy(w => w.Campaign)
            .ThenBy(w => w.Name, StringComparer.CurrentCultureIgnoreCase)
            .ToList();
    }

    /// <summary>The text of the name tag; a name that is not a tag as is; else the record's file name.</summary>
    private string DisplayName(string? nameTag, string record)
    {
        if (texts.GetText(nameTag) is { Length: > 0 } text)
            return StripFormatting(text);
        if (!string.IsNullOrWhiteSpace(nameTag) && !nameTag.StartsWith("tag", StringComparison.OrdinalIgnoreCase))
            return nameTag.Trim();
        return Path.GetFileNameWithoutExtension(record);
    }

    /// <summary>Removes the game's color codes (<c>^w</c>, <c>{^Y}</c>, ...) from a text.</summary>
    private static string StripFormatting(string text)
    {
        var builder = new System.Text.StringBuilder(text.Length);
        for (var i = 0; i < text.Length; i++)
        {
            if (text[i] == '{' && i + 3 < text.Length && text[i + 1] == '^' && text[i + 3] == '}')
            {
                i += 3;
                continue;
            }

            if (text[i] == '^' && i + 1 < text.Length && char.IsLetter(text[i + 1]))
            {
                i++;
                continue;
            }

            builder.Append(text[i]);
        }

        return builder.ToString().Trim();
    }
}
